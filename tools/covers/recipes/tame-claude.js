// 稳定不封号：一把纸白大锁顶住画面，左边一条墨线折线绕过几个节点（干净 IP、指纹浏览器……），
// 最后一支箭头钻进锁身——环境收拾干净再进门，号才锁得住
module.exports = {
  swatch: 'olive',
  seed: 5,
  draw(d, m) {
    // 主物件：大锁，偏右放，左边留出折线的位置
    d.at({ x: 645, y: 560, s: 1.28, rot: 3 }, () => m.lock(d));

    // 绕路：硬转角折线 + 墨点节点
    d.link([[95, 880], [240, 680], [90, 450], [225, 230]], { r: 26 });
    // 最后一段：离节点留空，箭头扎进锁身
    d.arrow([[262, 285], [460, 620]]);
  },
};
