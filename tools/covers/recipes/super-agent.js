// Super-agent：顶上一块宽纸白剪纸是 Router，只管分发；下面三张纸片是并行的 Worker。
// 墨线从 Router 中间的墨点往下分叉，三支箭头各自贯穿一张 Worker，从头干到尾
module.exports = {
  swatch: 'peach',
  seed: 3,
  draw(d, m) {
    // 纸片：Router
    d.cut([[70, 70], [930, 62], [924, 290], [76, 298]], { amp: 6 });
    // 纸片：三个 Worker，彼此和 Router 之间都隔开底色
    [[225, -2], [500, 1], [775, 2]].forEach(([x, rot]) => {
      d.at({ x, y: 665, rot }, () => d.cut(d.rect(-112, -255, 224, 510), { amp: 5 }));
    });
    // 墨线：Router 的分发点，主干从墨点往下，横向分叉到三个 Worker 头上
    d.link([[500, 175], [500, 352]], { r: 36, dots: [0] });
    d.link([[225, 352], [500, 352], [775, 352]], { r: 22, dots: [0, 2] });
    // 墨线：每个 Worker 一支箭头从顶走到底，各走各的路
    d.arrow([[225, 402], [190, 540], [262, 690], [225, 878]], { head: 40 });
    d.arrow([[500, 402], [535, 520], [468, 640], [530, 760], [500, 878]], { head: 40 });
    d.arrow([[775, 402], [745, 560], [808, 720], [775, 878]], { head: 40 });
  },
};
