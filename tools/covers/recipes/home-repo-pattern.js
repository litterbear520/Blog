// Home Repo 模式：左边一座纸白剪纸房子是 Home Repo，屋里一个墨点伸出三支箭头，
// 指向右侧三块小纸白方块，也就是 AGENTS.md 里的导航指针指向的其他仓库
module.exports = {
  swatch: 'coral',
  seed: 9,
  draw(d, m) {
    // 纸片：房子（屋顶 + 墙身一整块）
    d.cut([[70, 420], [320, 95], [570, 420], [570, 905], [70, 905]], { amp: 5 });
    // 纸片：三个其他仓库，和房子隔开底色
    [[205, -5], [500, 3], [795, -2]].forEach(([y, rot]) => {
      d.at({ x: 860, y, rot }, () => d.cut(d.rect(-80, -80, 160, 160), { amp: 4 }));
    });
    // 墨线：屋里的墨点是 AGENTS.md，三条指针伸向各个仓库
    d.dot(330, 560, 30);
    d.arrow([[375, 520], [745, 235]], { head: 36 });
    d.arrow([[385, 560], [745, 510]], { head: 36 });
    d.arrow([[375, 600], [745, 770]], { head: 36 });
  },
};
