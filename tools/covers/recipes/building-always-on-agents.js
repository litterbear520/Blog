// 构建始终在线的 Agent：一只纸白剪纸闹钟。Agent 大部分时间在睡，到点被叫醒干一次活，
// 看上去就像一直在线；闹钟右上方几道墨线表示它正在响
module.exports = {
  swatch: 'clay',
  seed: 7,
  draw(d) {
    d.at({ x: -32, y: -22, s: 1.06 }, () => {
      // 纸片：两只铃铛用深一档的底色，和钟面纸白交替，不会糊成一块
      d.at({ x: 255, y: 250, rot: -38 }, () => d.cut([[-105, 40], [-80, -45], [0, -80], [80, -45], [105, 40]], { color: d.tint, amp: 4 }));
      d.at({ x: 705, y: 250, rot: 38 }, () => d.cut([[-105, 40], [-80, -45], [0, -80], [80, -45], [105, 40]], { color: d.tint, amp: 4 }));
      // 纸片：钟面
      d.disc(480, 540, 330, { sides: 11 });
      // 墨线：两根指针和轴心
      d.brush([[480, 540], [480, 340]]);
      d.brush([[480, 540], [625, 625]]);
      d.dot(480, 540, 30);
      // 墨线：两条腿
      d.brush([[300, 810], [235, 905]]);
      d.brush([[660, 810], [725, 905]]);
      // 墨线：响铃的震动线
      d.brush([[830, 230], [900, 172]]);
      d.brush([[855, 330], [930, 312]]);
      d.brush([[760, 150], [800, 70]]);
    });
  },
};
