// 隐喻：三条弱模型的墨线汇成一个节点，再一箭落到领奖台的第二级（模型融合 → Top2）
module.exports = {
  swatch: 'cactus',
  seed: 7,
  draw(d, m) {
    // 领奖台：左 2nd 纸白、中 1st 用深一档底色（没拿到的第一）、右 3rd 纸白
    d.cut([[70, 560], [365, 560], [365, 930], [70, 930]]);
    d.cut([[365, 420], [635, 420], [635, 930], [365, 930]], { color: d.tint });
    d.cut([[635, 670], [930, 670], [930, 930], [635, 930]]);
    // 三条弱模型线从上方汇到一个节点
    const hub = [218, 330];
    d.link([[90, 90], [218, 330]], { r: 26, dots: [0] });
    d.link([[470, 70], [218, 330]], { r: 26, dots: [0] });
    d.link([[900, 140], [560, 250], [218, 330]], { r: 26, dots: [0, 1] });
    d.dot(hub[0], hub[1], 36);
    // 融合后的一箭落到第二级，箭头压在纸片上
    d.arrow([[218, 400], [218, 700]], { head: 56 });
  },
};
