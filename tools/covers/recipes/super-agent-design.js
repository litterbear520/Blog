// Super-agent 设计探索：同一个 Agent 在 IM 和 GitHub 之间连续推进一件事。
// 左上一块纸白对话气泡是群聊，右下一张纸白文档是 Pull Request，两块之间隔着底色；
// 一条墨线从气泡里的墨点出发，跨过缝隙一路不断地走进文档，末端是箭头
module.exports = {
  swatch: 'peach',
  seed: 5,
  draw(d, m) {
    // 纸片：对话气泡，左下角一个尖尾
    d.at({ x: 285, y: 400, rot: -3 }, () => {
      d.cut([[-235, -320], [235, -330], [245, 230], [-60, 240], [-190, 370], [-150, 240], [-240, 235]], { amp: 6 });
    });
    // 纸片：PR 文档，和气泡之间留一道底色缝
    d.at({ x: 772, y: 590, s: 0.86, rot: 2 }, () => m.doc(d));
    // 墨线：一条连续的线，从气泡里出发，跨过缝隙进到文档里
    d.link([[150, 250], [330, 330], [190, 470], [400, 540]], { r: 26, dots: [0, 1, 2, 3] });
    d.arrow([[400, 540], [520, 560], [600, 520], [700, 560], [760, 680]], { head: 46 });
  },
};
