// mod 就是挂进终端会话的一串 hook：纸白终端窗口上，一条墨线串起四个节点往下传，
// 第二个节点弯回一支箭头（作答，不再往下传）；右下角是终端提示符
module.exports = {
  swatch: 'clay',
  seed: 23,
  draw(d, m) {
    d.at({ x: 500, y: 500, s: 1.28 }, () => {
      m.window(d);
      // 事件依次经过各个 hook：四个墨点连成一条链
      d.link([[-250, -60], [-85, -60], [85, -60], [250, -60]], { r: 30 });
      // 作答：从第二个节点弯回第一个
      d.arrow([[-85, 0], [-115, 120], [-220, 120], [-250, 10]], { head: 34 });
      // 终端提示符 >_
      d.brush([[90, 70], [150, 120], [90, 170]], { w: 26, amp: 1, taper: 0.05 });
      d.brush([[185, 170], [260, 170]], { w: 26, amp: 1 });
    });
  },
};
