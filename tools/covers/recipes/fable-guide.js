// 地图并非疆域：一张三折纸地图，墨线路线走到尽头变成虚线，放大镜压在路线外那片空白上——那里就是还没摸清的未知
module.exports = {
  swatch: 'mineral',
  seed: 7,
  draw(d, m) {
    // 三折地图：中间一折用深一档底色，像折痕背光的那一面，左右两折是纸白
    d.cut([[70, 250], [360, 190], [360, 790], [70, 850]]);
    d.cut([[360, 190], [640, 250], [640, 850], [360, 790]], { color: d.tint });
    d.cut([[640, 250], [930, 190], [930, 790], [640, 850]]);
    // 已知的路线：黑点连成的折线
    d.link([[140, 380], [250, 610], [400, 500], [520, 710]], { r: 26 });
    // 路线之后是虚线，朝放大镜下那片空白走去，停在镜框外
    d.dashed([[575, 700], [650, 650], [700, 575]], { dash: 36, gap: 30 });
    // 放大镜压在右上那片空白上，不带纸白镜片
    d.at({ x: 730, y: 400, s: 0.7 }, () => m.magnifier(d, { lens: false }));
  },
};
