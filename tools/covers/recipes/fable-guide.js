// 探索你的未知领域：一张折起的地图，虚线路线走到尽头，放大镜停在那里找「未知」
module.exports = {
  swatch: 'mineral',
  seed: 5,
  draw(d, m) {
    d.at({ x: 470, y: 520, rot: -4 }, () => {
      d.paper(d.rect(-380, -250, 760, 500), { shift: [26, -22], w: 24, jag: 6 });
      d.brush([[-127, -250], [-127, 250]], { w: 18, amp: 2 });
      d.brush([[127, -250], [127, 250]], { w: 18, amp: 2 });
      d.dashed([[-310, 170], [-180, -40], [-20, 150], [130, -60], [300, 20]], { w: 18, dash: 40, gap: 32 });
    });
    d.at({ x: 780, y: 470, s: 0.62, rot: 10 }, () => m.magnifier(d));
    d.sparkle(140, 150, 110, 22);
  },
};
