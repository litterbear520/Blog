// 自己拿卡去订阅：一张大银行卡压在另一张卡上，前面这张是纸白、墨线画磁条和芯片
module.exports = {
  swatch: 'peach',
  seed: 7,
  draw(d, m) {
    // 后面那张卡：深一档底色，往右上错开，只露出一角
    d.at({ x: 580, y: 385, s: 0.95, rot: 6 }, () => {
      d.cut(d.rect(-370, -230, 740, 460), { amp: 5, color: d.tint });
    });
    // 主物件：银行卡剪影，墨线画磁条和芯片（压在纸片上）
    d.at({ x: 450, y: 580, s: 1.05, rot: -10 }, () => {
      d.cut(d.rect(-370, -230, 740, 460), { amp: 5 });
      d.brush([[-366, -110], [366, -110]], { w: 20, amp: 1.5 });
      d.brush(d.rect(-250, -75, 130, 100), { w: 20, amp: 1, closed: true, smooth: false });
    });
  },
};
