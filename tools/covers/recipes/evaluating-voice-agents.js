// 如何评估语音代理：要评估的是通话，而不是文字。一只大纸白电话听筒横跨画面（通话本身），
// 弧内是一排墨线声波，一个大对勾从下方压上听筒——打分的对象是听得见的声音，不是转写文本
module.exports = {
  swatch: 'cactus',
  seed: 7,
  draw(d, m) {
    // 纸片：电话听筒，弧形手柄两头是听筒和话筒，开口朝下
    d.cut(
      [
        [55, 455], [40, 300], [115, 185], [270, 110], [500, 80], [730, 110], [885, 185], [960, 300], [945, 455],
        [735, 470], [720, 345], [640, 285], [500, 265], [360, 285], [280, 345], [265, 470],
      ],
      { amp: 5 },
    );
    // 墨线：声波，一排高低不一的竖笔，收在听筒弧内
    const hs = [80, 180, 300, 200, 80];
    hs.forEach((h, i) => {
      const x = 330 + i * 80;
      d.brush([[x, 470 - h / 2], [x, 470 + h / 2]], { amp: 1 });
    });
    // 墨线：大对勾，长笔一直压到听筒右端的纸片上
    d.brush([[245, 705], [430, 885], [905, 395]], { smooth: false, amp: 1 });
  },
};
