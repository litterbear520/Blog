// 更有雄心地使用 AI：文章配图是戈雅的《飞行之法》——一对剪纸蝙蝠翼往上扬，墨线翼骨沿前缘伸到翼尖、
// 再从腕部散向后缘的两个翼尖；一支箭头从两翼之间的缝里笔直往上穿出去：飞得更高
module.exports = {
  swatch: 'coral',
  seed: 5,
  draw(d, m) {
    // 右翼（局部原点在两翼中缝）：前缘斜向上到翼尖，后缘剪出两道蝙蝠翼似的缺口；左翼镜像
    const wing = [[45, -40], [240, -230], [445, -400], [345, -150], [450, -60], [295, 0], [320, 200], [170, 110], [45, 190]];
    for (const flip of [false, true]) {
      d.at({ x: 500, y: 560, flip }, () => {
        d.cut(wing, { amp: 5 });
        // 翼骨：前缘一根到翼尖，腕部再散出两根指骨
        d.brush([[95, 20], [245, -175], [395, -330]], { amp: 1.5 });
        d.brush([[245, -175], [330, -90], [395, -60]], { amp: 1.5 });
        d.brush([[245, -175], [270, -20], [290, 140]], { amp: 1.5 });
      });
    }
    // 箭头从两翼之间穿出去
    d.arrow([[500, 920], [500, 80]], { head: 44 });
  },
};
